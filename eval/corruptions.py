"""Corruption transforms — cheap, auditable ground truth for the critic benchmark.

Hand-writing borderline cases is slow and the labels drift with the author's mood.
Instead: take an answer already labelled "good", apply a transform that is defensibly
answer-degrading, and inherit the label "poor" from the transform. You audit four
transforms once rather than twenty answers individually.

THE RULE EVERY TRANSFORM HERE OBEYS
-----------------------------------
A corruption must be detectable from the (query, answer) pair ALONE.

`CRITIC_PROMPT` in `app/agent/nodes/critic.py` interpolates exactly two fields, Query
and Answer — it never receives the retrieved context. So a corruption that only
contradicts a *source* yields a case the critic cannot get right at any quality level.
Such a case would measure a missing prompt field, not critic accuracy, and labelling it
"poor" poisons the dataset. This is why `contradict_source` does not exist here, and why
`overclaim` (append a plausible fabricated specific) and `drop_citation` were also cut:
without the source text, an invented version number and a real one are indistinguishable,
and a de-hedged answer reads *better*, not worse. See
`docs/superpowers/specs/2026-08-15-corruption-gen-design.md`.

Transforms are pure and deterministic — no LLM call, no randomness. The benchmark
already has one unreproducible component (the critic samples at the provider default
temperature); a second one in the dataset would make a score change uninterpretable,
because you could not tell a prompt regression from a re-rolled dataset.
"""

from __future__ import annotations

import re
from typing import Callable

from eval.cases import BENCHMARK_CASES, CASES, CriticCase

Transform = Callable[[CriticCase], "CriticCase | None"]

# Split on sentence-final punctuation followed by whitespace. The whitespace is what
# keeps version strings intact: the "." in "bge-small-en-v1.5" is followed by a digit.
_SENTENCE_BOUNDARY = re.compile(r"(?<=[.!?])\s+")

_SOURCES_MARKER = "\n\nSources:"


def _split_sources(answer: str) -> tuple[str, str]:
    """Separate the prose body from the trailing `Sources:` block.

    Transforms rewrite the body and re-attach the block untouched — a corruption that
    silently dropped citations would be testing two things at once.
    """
    body, sep, rest = answer.partition(_SOURCES_MARKER)
    return body.rstrip(), (sep + rest) if sep else ""


def _derive(seed: CriticCase, answer: str, transform: str, why: str) -> CriticCase:
    """Build the corrupted case, forcing the label to "poor"."""
    return CriticCase(
        label=f"{seed.label}__{transform}",
        query=seed.query,
        answer=answer,
        expected="poor",
        reason=(
            f"Generated by {transform}() from '{seed.label}' — {why}. "
            "Label is inherited from the transform, not a fresh human judgement."
        ),
        # Provenance only. Never reaches the critic; it exists so a human auditing a
        # generated case can check the transform was fair.
        context=seed.context,
    )


# ---------------------------------------------------------------------------
# Transforms
#
# Each returns None when it does not apply. A transform that returned its input
# unchanged would emit a "good" answer labelled "poor" — the single most damaging
# bug this module can have, so `generate()` asserts against it as well.
# ---------------------------------------------------------------------------

# Ordered: the specific verbs first, " is "/" are " last, so "DocChat supports X" is
# negated on "supports" rather than on an incidental "is" later in the sentence.
_NEGATIONS: tuple[tuple[str, str], ...] = (
    (" supports ", " does not support "),
    (" provides ", " does not provide "),
    (" uses ", " does not use "),
    (" expire ", " do not expire "),
    (" has ", " does not have "),
    (" are ", " are not "),
    (" is ", " is not "),
)


def contradict_self(case: CriticCase) -> CriticCase | None:
    """Append a clause asserting the negation of the answer's own opening claim.

    Self-contradiction is the one contradiction the critic can see without the source,
    which is why it replaces the `contradict_source` this module was originally
    sketched with.
    """
    body, sources = _split_sources(case.answer)
    if not body:
        return None

    opening = _SENTENCE_BOUNDARY.split(body)[0]
    for verb, negated in _NEGATIONS:
        if verb in opening:
            flipped = opening.replace(verb, negated, 1)
            break
    else:
        return None

    corrupted = f"{body} However, that is not correct: {flipped}"
    return _derive(
        case,
        corrupted + sources,
        "contradict_self",
        "the answer now asserts both a claim and its negation",
    )


# A "specific" is the concrete detail a factual query is actually asking for: a
# hyphenated or slashed identifier, a number, or an internally-capitalised product name.
_SPECIFIC = re.compile(
    r"\b(?:"
    r"[A-Za-z]\w*(?:[-/][\w.]+)+"   # BAAI/bge-small-en-v1.5, youtube-transcript-api
    r"|(?<!\()\d[\w.-]*"             # 384, 30 — but never the "(1)" of an enumeration,
    r"|[A-Za-z]+[A-Z][A-Za-z]*"     # PyMuPDF, SQLAlchemy, PostgreSQL, ONNX
    r")\b"
)
# …because "(1)" is structure, not a detail the query asked for. Redacting it turns a
# vagueness corruption into a malformed-list one and muddies which mode is being tested.

# The subject of the answer is not one of its specifics. Redacting it produces
# gibberish rather than a vague-but-fluent answer, which is a different failure mode.
_KEEP = frozenset({"DocChat", "YouTube", "PDFs", "PDF"})

_REDACTION = "[redacted]"


def strip_specifics(case: CriticCase) -> CriticCase | None:
    """Redact the concrete details, leaving fluent prose that answers nothing.

    Reproduces the `vague_no_substance` failure mode. Requires at least two distinct
    specifics: redacting a lone one usually leaves the query still answered, and the
    single-specific seeds here are the gap-admission cases, which this would turn into
    a different failure mode than intended.
    """
    body, sources = _split_sources(case.answer)
    found = {m.group(0) for m in _SPECIFIC.finditer(body) if m.group(0) not in _KEEP}
    if len(found) < 2:
        return None

    corrupted = _SPECIFIC.sub(
        lambda m: m.group(0) if m.group(0) in _KEEP else _REDACTION, body
    )
    return _derive(
        case,
        corrupted + sources,
        "strip_specifics",
        "every concrete detail the query asked for has been redacted",
    )


_ENUMERATION = re.compile(r"\s*\(\d+\)\s")


def truncate_enumeration(case: CriticCase) -> CriticCase | None:
    """Delete the final enumerated clause of a multi-part answer.

    Reproduces `incomplete_two_part_query`, the critic's most common real miss. Only
    fires on explicit "(1) … (2) … (3)" enumeration: sentence-level truncation looked
    equivalent but is not, because an answer's last sentence is often elaboration
    rather than a queried part, and cutting it would leave the query still answered.
    """
    body, sources = _split_sources(case.answer)
    marks = list(_ENUMERATION.finditer(body))
    if len(marks) < 2:
        return None

    truncated = body[: marks[-1].start()].rstrip().rstrip(";,") + "."
    return _derive(
        case,
        truncated + sources,
        "truncate_enumeration",
        f"the answer promises {len(marks)} parts and now delivers {len(marks) - 1}",
    )


# Rotating by three guarantees the donor answer is about a different subject than the
# query. It is a fixed offset rather than a random pick so the dataset stays byte-stable.
_SWAP_OFFSET = 3


def _off_topic_swap(case: CriticCase, donor: CriticCase) -> CriticCase | None:
    """Pair a query with a fluent, correct answer to an unrelated question."""
    if donor.answer == case.answer:
        return None
    return _derive(
        case,
        donor.answer,
        "off_topic_swap",
        f"the body is the (correct) answer to '{donor.label}' instead",
    )


TRANSFORMS: tuple[Transform, ...] = (
    contradict_self,
    strip_specifics,
    truncate_enumeration,
)


# Seeds are drawn from BOTH case lists. Reading `CASES` here does not couple the two
# layers: the output goes to the benchmark only, and generated labels are
# "{seed}__{transform}", so they never collide with a Layer B label.
SEEDS: tuple[CriticCase, ...] = tuple(
    c for c in (*BENCHMARK_CASES, *CASES) if c.expected == "good"
)


def generate(seeds: list[CriticCase] | None = None) -> list[CriticCase]:
    """Every applicable (seed, transform) pair, plus the off-topic rotation.

    Only `expected="good"` seeds are usable — corrupting an already-poor answer yields
    a result nobody can label.
    """
    pool = [c for c in (seeds if seeds is not None else SEEDS) if c.expected == "good"]

    generated: list[CriticCase] = []
    for transform in TRANSFORMS:
        for seed in pool:
            corrupted = transform(seed)
            if corrupted is not None:
                generated.append(corrupted)

    for i, seed in enumerate(pool):
        corrupted = _off_topic_swap(seed, pool[(i + _SWAP_OFFSET) % len(pool)])
        if corrupted is not None:
            generated.append(corrupted)

    # A transform that no-ops emits a good answer labelled poor. Fail loudly instead.
    by_answer = {c.label: c.answer for c in pool}
    for case in generated:
        seed_label = case.label.rsplit("__", 1)[0]
        assert case.answer != by_answer[seed_label], (
            f"{case.label} is identical to its seed — the transform silently no-opped "
            "and would inject a mislabelled case"
        )

    return generated
